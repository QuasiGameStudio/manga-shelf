    private static final Color CLEAR = new Color(0.32f, 0.24f, 0.42f, 1f);
    private static final Color TEXT = new Color(1f, 0.96f, 0.87f, 1f);
    private static final Color TEXT_DARK = new Color(0.30f, 0.18f, 0.11f, 1f);
